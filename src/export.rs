use crate::{
    catalogue::{Catalogue, value},
    project::{Mode, Project, Reload},
};
use anyhow::{Context, Result, ensure};
use ghostline_red::tweakdb::TweakId;
use serde::Serialize;
use serde_json::{Value, json};
use std::io::{Cursor, Write};

#[derive(Serialize)]
pub struct Review {
    pub target: String,
    pub yaml: String,
    pub changes: Vec<Value>,
    pub warnings: Vec<String>,
    pub spawn_command: Option<String>,
    pub dependencies: Vec<String>,
}

fn change(changes: &mut Vec<Value>, field: &str, before: Value, after: Value, reason: &str) {
    changes.push(json!({"field":field,"before":before,"after":after,"reason":reason}));
}

pub fn review(c: &Catalogue, p: &Project) -> Result<Review> {
    p.validate()?;
    ensure!(
        p.catalogue == c.identity,
        "project source catalogue has changed; create a fresh project or explicitly rebase it"
    );
    let item = c.item(&p.item)?;
    let source = item["native_name"]
        .as_str()
        .context("native record name missing")?;
    let target = if p.mode == Mode::Replace {
        source.to_owned()
    } else {
        p.record.clone()
    };
    if p.mode == Mode::Variant {
        ensure!(
            !c.native_names.contains(&target),
            "variant record already exists in the native catalogue"
        );
    }
    let mut yaml = format!(
        "# Generated by Ghostline Item Builder\n# Source: {source}\n{}:\n",
        serde_json::to_string(&target)?
    );
    if p.mode == Mode::Variant {
        yaml.push_str(&format!("  $base: {}\n", serde_json::to_string(source)?));
    }
    let mut changes = Vec::new();
    let mut warnings=vec!["Stats, reload animations and appearance selection require in-game playtesting. Catalogue images show native appearances, not simulated combat stats.".into()];
    if p.mode == Mode::Variant || p.appearance.is_some() || !p.recolours.is_empty() {
        let icon = if !p.recolours.is_empty() {
            crate::icons::generated_icon(&p.id)
        } else {
            crate::icons::source_icon(item).unwrap_or_else(||{
            warnings.push("The source inventory icon could not be resolved; using the native weapon-category icon.".into());
            "Weapon".into()
        })
        };
        yaml.push_str(&format!("  iconPath: {}\n", serde_json::to_string(&icon)?));
        change(
            &mut changes,
            "inventory icon",
            value(item, "iconPath").clone(),
            json!(icon),
            if p.recolours.is_empty() {
                "Pin the source inventory image so new record and appearance identities do not break automatic icon lookup"
            } else {
                "Generate an inventory atlas from the recoloured side-view render"
            },
        );
    }
    let mut modifiers = Vec::<(String, &str, &str, f64)>::new();
    let prefix = format!("Items.GhostlineIB_{}", p.id);
    if let Some(iconic) = p.iconic {
        modifiers.push((
            format!("{prefix}_Iconic"),
            "IsItemIconic",
            if iconic { "Additive" } else { "Multiplier" },
            if iconic { 1. } else { 0. },
        ));
        change(
            &mut changes,
            "Iconic status",
            json!("inherited"),
            json!(iconic),
            "Iconic is a separate native stat flag, independent of quality; it does not create unique weapon abilities",
        );
    }
    if p.damage_multiplier != 1. {
        modifiers.push((
            format!("{prefix}_Damage"),
            "DPS",
            "Multiplier",
            p.damage_multiplier,
        ));
        change(
            &mut changes,
            "damage multiplier",
            json!(1.),
            json!(p.damage_multiplier),
            "Multiplies native DPS; per-hit damage remains calculated by the game from weapon stats, level and bonuses",
        );
    }
    if p.magazine_bonus != 0. {
        modifiers.push((
            format!("{prefix}_Magazine"),
            "MagazineCapacityBonus",
            "Additive",
            p.magazine_bonus,
        ));
        change(
            &mut changes,
            "magazine size bonus",
            json!(0.),
            json!(p.magazine_bonus),
            "Adds to the native magazine capacity bonus without replacing base capacity or shared records",
        );
    }
    if p.reload_time_bonus != 0. {
        modifiers.push((
            format!("{prefix}_ReloadTime"),
            "ReloadTimeBonus",
            "Additive",
            p.reload_time_bonus,
        ));
        change(
            &mut changes,
            "reload time change",
            json!(0.),
            json!(p.reload_time_bonus),
            "Adds a native reload time bonus; negative is faster. Does not create a reload mechanic on its own",
        );
    }
    if let Some(rarity) = &p.rarity {
        yaml.push_str(&format!(
            "  quality: Quality.{rarity}\n  qualityRestrictedByParent: false\n"
        ));
        change(
            &mut changes,
            "quality",
            value(item, "quality").clone(),
            json!(format!("Quality.{rarity}")),
            "Pins native quality and removes random-quality stat modifiers on this record only",
        );
    }
    if p.reload != Reload::Original {
        ensure!(
            item["item_type"] == "Wea_Handgun",
            "the linked reload operation currently supports handguns"
        );
        let original = value(item, "tags")
            .as_array()
            .context("native tags missing")?;
        let mut tags: Vec<Value> = original
            .iter()
            .filter(|v| v.as_str() != Some("DiscardOnEmpty"))
            .cloned()
            .collect();
        tags.dedup();
        if p.reload == Reload::Reloadable {
            ensure!(
                original.iter().any(|v| v == "DiscardOnEmpty")
                    && value(item, "baseReloadTime").as_f64() == Some(0.)
                    && value(item, "baseEmptyReloadTime").as_f64() == Some(0.),
                "reload conversion requires a native disposable handgun with zero reload baselines; ordinary weapons should keep original reload behaviour"
            );
            let donor = c
                .items
                .values()
                .find(|i| i["native_name"] == "Items.Base_Unity")
                .context("native Unity reload donor missing")?;
            ensure!(
                value(donor, "ammo")
                    == &json!(TweakId::from_name("Ammo.HandgunAmmo").0.to_string()),
                "Unity ammo no longer matches the established native profile"
            );
            for field in [
                "stateMachineName",
                "baseReloadTime",
                "baseEmptyReloadTime",
                "uninterruptibleReloadStart",
                "uninterruptibleEmptyReloadStart",
            ] {
                let after = value(donor, field);
                ensure!(!after.is_null(), "reload donor property {field} absent");
                yaml.push_str(&format!("  {field}: {}\n", serde_json::to_string(after)?));
                change(
                    &mut changes,
                    field,
                    value(item, field).clone(),
                    after.clone(),
                    "Native Items.Base_Unity reload profile",
                );
            }
            yaml.push_str("  ammo: Ammo.HandgunAmmo\n");
            change(
                &mut changes,
                "ammo",
                value(item, "ammo").clone(),
                json!("Ammo.HandgunAmmo"),
                "Use standard reserve handgun ammunition rather than the disposable weapon's ammo record",
            );
            for (field, stat, amount) in [
                ("Reload", "ReloadTimeBase", 0.75),
                ("EmptyReload", "EmptyReloadTime", 0.75),
                ("ReloadEnd", "ReloadEndTimeBase", 0.35),
                ("EmptyReloadEnd", "EmptyReloadEndTime", 1.25),
            ] {
                modifiers.push((format!("{prefix}_{field}"), stat, "Additive", amount));
            }
            warnings.push("Reload conversion retains the original weapon mesh and animation resources. Missing native reload clips are not replaced with another weapon's clips. Verify the reload presentation in game.".into());
        } else {
            tags.push(json!("DiscardOnEmpty"));
            yaml.push_str("  stateMachineName: HeavyWeapon\n");
            change(
                &mut changes,
                "stateMachineName",
                value(item, "stateMachineName").clone(),
                json!("HeavyWeapon"),
                "Native disposable-handgun state-machine profile",
            );
            warnings.push("Disposable mode discards the weapon when empty. Existing save-game instances may need to be replaced after changing its behaviour.".into());
        }
        yaml.push_str(&format!("  tags: {}\n", serde_json::to_string(&tags)?));
        change(
            &mut changes,
            "tags",
            json!(original),
            json!(tags),
            "Change discard-on-empty behaviour while retaining unrelated native tags",
        );
    }
    if let Some(id) = &p.appearance {
        let selection = c
            .selections(item)?
            .into_iter()
            .find(|s| s["id"] == *id)
            .context("appearance does not belong to this weapon")?;
        ensure!(
            selection["resolution"] == "resolved",
            "appearance has unresolved bindings"
        );
        let appearance = selection["appearance"]
            .as_str()
            .context("appearance name missing")?;
        ensure!(!appearance.is_empty(), "appearance name is empty");
        yaml.push_str(&format!(
            "  appearanceName: {}\n",
            serde_json::to_string(appearance)?
        ));
        change(
            &mut changes,
            "appearanceName",
            value(item, "appearanceName").clone(),
            json!(appearance),
            "Exact native appearance selected from this weapon's catalogue entries; preserves its registered appearance resource",
        );
        if p.recolours.is_empty() {
            warnings.push("Existing appearance selection uses native colours. Native part/preset appearance rules still apply; verify assembled appearance in game.".into());
        }
    }
    if !p.recolours.is_empty() {
        yaml.push_str(&format!(
            "  appearanceResourceName: {}\n",
            crate::recolour::factory(p)
        ));
        for edit in &p.recolours {
            change(
                &mut changes,
                "material layer colour",
                json!(edit.region),
                json!(edit.colour),
                "Project-owned multilayer setup and template; native masks and textures retained",
            );
        }
        warnings.push("Custom colours require ArchiveXL as well as RED4ext and TweakXL. The generated appearance uses project-owned material resources; verify native weapon-part assembly in game.".into());
    }
    if !modifiers.is_empty() || p.rarity.is_some() {
        yaml.push_str("  statModifiers:\n");
        if p.rarity.is_some() {
            for name in [
                "Items.QualityRandomization",
                "Items.IconicQualityRandomization",
                "Items.ItemPlusRandomizer_MaxQuality",
                "Items.ItemPlusRandomizer_Below_MaxQuality",
            ] {
                yaml.push_str(&format!("    - !remove {name}\n"));
            }
        }
        for (record, _, _, _) in &modifiers {
            yaml.push_str(&format!("    - !append-once {record}\n"));
        }
    }
    if !p.recolours.is_empty() {
        yaml.push_str(&format!("\nUIIcon.{}:\n  $type: UIIcon\n  atlasResourcePath: mod\\ghostline_item_builder\\{}\\inventory.inkatlas\n  atlasPartName: inventory\n",crate::icons::generated_icon(&p.id),p.id));
    }
    for (record, stat, kind, number) in modifiers {
        yaml.push_str(&format!("\n{record}:\n  $type: gamedataConstantStatModifier_Record\n  statType: BaseStats.{stat}\n  modifierType: {kind}\n  value: {number}\n"));
    }
    if p.mode == Mode::Variant {
        warnings.push("A separate variant is not automatically added to shops or loot. Use the supplied CET spawn command to acquire it.".into());
    }
    if item["selections"].as_array().is_none_or(Vec::is_empty) {
        warnings.push("This is a base/template record with no published appearance preview. Prefer a concrete Preset record for a spawnable variant.".into());
    }
    if changes.is_empty() && p.mode == Mode::Replace {
        warnings.push("No edits selected; this replacement has no effect.".into());
    }
    Ok(Review {
        target: target.clone(),
        yaml,
        changes,
        warnings,
        spawn_command: Some(format!(
            "Game.AddToInventory({}, 1)",
            serde_json::to_string(&target)?
        )),
        dependencies: if p.recolours.is_empty() {
            vec!["RED4ext".into(), "TweakXL".into()]
        } else {
            vec!["RED4ext".into(), "TweakXL".into(), "ArchiveXL".into()]
        },
    })
}

pub fn package(
    c: &Catalogue,
    p: &Project,
    native: Option<&crate::recolour::Native>,
) -> Result<Vec<u8>> {
    let assets = if p.recolours.is_empty() {
        None
    } else {
        Some(
            native
                .context("custom colours require --game")?
                .build(c, p)?,
        )
    };
    let report = review(c, p)?;
    let mut zip = zip::ZipWriter::new(Cursor::new(Vec::new()));
    let options =
        zip::write::SimpleFileOptions::default().compression_method(zip::CompressionMethod::Stored);
    if let Some(assets) = assets {
        zip.start_file(
            format!("archive/pc/mod/ghostline_ib_{}.archive", p.id),
            options,
        )?;
        zip.write_all(&assets.archive)?;
        zip.start_file(
            format!("archive/pc/mod/ghostline_ib_{}.archive.xl", p.id),
            options,
        )?;
        zip.write_all(assets.xl.as_bytes())?;
        zip.start_file("inventory-icon.png", options)?;
        zip.write_all(&assets.inventory_icon)?;
    }
    let readme = format!(
        "{}\n\nRequires {}.\nExtract this ZIP into your Cyberpunk 2077 directory, retaining r6 and archive folders.\nTo uninstall, remove r6/tweaks/ghostline-item-builder/{}.yaml and, when present, archive/pc/mod/ghostline_ib_{}.archive and its .archive.xl sidecar.\n\nSource: {}\nTarget: {}\n\nAcquire for testing in CET:\n{}\n\n{}\n\nCatalogue source: {}\n",
        p.title,
        report.dependencies.join(", "),
        p.id,
        p.id,
        c.item(&p.item)?["native_name"],
        report.target,
        report.spawn_command.as_deref().unwrap_or(""),
        report.warnings.join("\n"),
        c.sources
    );
    for (name, bytes) in [
        (
            format!("r6/tweaks/ghostline-item-builder/{}.yaml", p.id),
            report.yaml.as_bytes().to_vec(),
        ),
        ("project.item.json".into(), serde_json::to_vec_pretty(p)?),
        ("report.json".into(), serde_json::to_vec_pretty(&report)?),
        ("README.txt".into(), readme.into_bytes()),
    ] {
        zip.start_file(name, options)?;
        zip.write_all(&bytes)?;
    }
    Ok(zip.finish()?.into_inner())
}

#[cfg(test)]
mod compatibility_tests {
    use super::*;

    #[test]
    fn reload_conversion_uses_donor_properties_across_catalogue_versions() {
        for version in ["2.31", "2.5"] {
            let root = tempfile::tempdir().unwrap();
            std::fs::create_dir(root.path().join("data")).unwrap();
            let descriptor = json!({"format":"ghostline-items","version":1,
                "sources":{"game_version":version},
                "collections":{"items":["data/items.json"],"selections":[]}});
            let rows = json!([
                {"id":"disposable","native_name":"Items.Test_Disposable","item_type":"Wea_Handgun",
                 "properties":{"tags":{"value":["DiscardOnEmpty"]},
                 "baseReloadTime":{"value":0.0},"baseEmptyReloadTime":{"value":0.0}}},
                {"id":"donor","native_name":"Items.Base_Unity","item_type":"Wea_Handgun",
                 "properties":{"ammo":{"value":TweakId::from_name("Ammo.HandgunAmmo").0.to_string()},
                 "stateMachineName":{"value":"Handgun"},"baseReloadTime":{"value":1.0},
                 "baseEmptyReloadTime":{"value":1.0},"uninterruptibleReloadStart":{"value":0.0},
                 "uninterruptibleEmptyReloadStart":{"value":0.0}}}
            ]);
            for (path, value) in [
                ("data/catalogue.json", descriptor),
                ("data/items.json", rows),
            ] {
                std::fs::write(root.path().join(path), serde_json::to_vec(&value).unwrap())
                    .unwrap();
            }
            let mut catalogue = Catalogue::load(root.path()).unwrap();
            let mut project = Project::new(
                "compatibility".into(),
                "disposable".into(),
                catalogue.identity.clone(),
            );
            project.mode = Mode::Replace;
            project.reload = Reload::Reloadable;
            let result = review(&catalogue, &project).unwrap();
            assert!(result.yaml.contains("ammo: Ammo.HandgunAmmo"));
            assert!(result.yaml.contains("stateMachineName: \"Handgun\""));

            catalogue.items.get_mut("donor").unwrap()["properties"]["ammo"]["value"] =
                json!("wrong-ammo");
            assert!(
                review(&catalogue, &project)
                    .err()
                    .unwrap()
                    .to_string()
                    .contains("Unity ammo")
            );
        }
    }
}
